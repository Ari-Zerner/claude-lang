def literals(node):
    """(Int literals, String literals) inside node, in order, except that the Ints compared with something
    (`income < 40000`) come first: those are where the branches are. `-5` counts as -5."""
    compared, other, strs = [], [], []

    def walk(x, in_cmp=False, neg=False):
        if isinstance(x, (list, tuple)):
            for y in x:
                walk(y)
            return
        if not hasattr(x, "kind") or not hasattr(x, "__dict__"):
            return
        if x.kind == "int":
            (compared if in_cmp else other).append(-x.value if neg else x.value)
        elif x.kind == "neg":
            walk(x.expr, in_cmp, not neg)
        elif x.kind == "str" and all(kind == "text" for kind, _ in x.parts):
            strs.append("".join(p for _, p in x.parts))
        elif x.kind == "bin" and x.op in ("==", "!=", "<", "<=", ">", ">="):
            walk(x.left, True)
            walk(x.right, True)
        else:
            for k, v in vars(x).items():
                if k not in ("tok", "name_tok", "end_tok", "var_tok", "ty", "var_ty") and (
                        isinstance(v, (list, tuple)) or hasattr(v, "kind")):
                    walk(v)
    walk(node)
    return compared + other, strs


def small_of(t, d, me=None, lowered=False):
    """Lean for the Array of small values of claude-lang type t at depth d (a Lean Nat term), with no type
    classes, like `fmt_of`. Depth bounds the size of an Int and the length and nesting of a list. Inside the
    generator of struct or enum `me`, a value of `me` itself comes from one depth lower, so generation stops;
    `lowered` says d already is lower (the path went through a list). `cl_si` and `cl_ss` are in scope
    wherever this goes: the Int and String seeds of the function being searched (`seeds`)."""
    ty = ltype(t, "the counterexample search")
    if t == "Int":
        e = f"clSmallInt cl_si {d}"
    elif t == "Bool":
        e = "clSmallBool"
    elif t == "String":
        e = f"clSmallString cl_ss {d}"
    elif is_list(t):
        e = (f"if {d} == 0 then #[#[]] else clSmallArrays {small_of(t[5:-1], f'({d} - 1)', me, True)} "
             f"(min {d} 4) {CX_CAP}")
    elif is_option(t):
        e = f"clSmallOption {small_of(targs(t)[0], d, me, lowered)}"
    elif is_result(t):
        a, b = targs(t)
        e = f"clSmallResult {small_of(a, d, me, lowered)} {small_of(b, d, me, lowered)}"
    elif t in STRUCTS or t in ENUMS:
        if t == me and not lowered:
            e = f"if {d} == 0 then #[] else T_{t}.clSmall cl_si cl_ss ({d} - 1)"
        else:
            e = f"T_{t}.clSmall cl_si cl_ss {d}"
    else:
        raise Unsupported(f"small values of a `{t}`")
    return f"(({e}) : Array {ty})"


def lean_str(t):
    out = []
    for ch in t:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


LTYPE = {"Int": "Int", "Bool": "Bool", "String": "String", "Unit": "Unit"}


STRUCTS = {}  # struct name -> its declaration; set by LeanEmitter, read by ltype and showable
ENUMS = {}  # enum name -> its declaration (variants: [(name, fields, tok)])


def targs(t):
    """The type arguments of `Option[T]` / `Result[T, E]` / `List[T]`, split at top-level commas."""
    inner, out, depth, cur = t[t.index("[") + 1:-1], [], 0, ""
    for ch in inner:
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        depth += {"[": 1, "]": -1}.get(ch, 0)
        cur += ch
    return out + [cur.strip()]


def is_option(t):
    return isinstance(t, str) and t.startswith("Option[")


def is_result(t):
    return isinstance(t, str) and t.startswith("Result[")


def is_list(t):
    return isinstance(t, str) and t.startswith("List[") and t.endswith("]")


def ltype(t, where):
    if t in LTYPE:
        return LTYPE[t]
    if is_list(t):
        return f"(Array {ltype(t[5:-1], where)})"
    if t in STRUCTS or t in ENUMS:
        return f"T_{t}"
    if is_option(t):
        return f"(Option {ltype(targs(t)[0], where)})"
    if is_result(t):
        a, b = targs(t)
        return f"(ClResult {ltype(a, where)} {ltype(b, where)})"
    raise Unsupported(f"the type `{t}` ({where})")


def showable(t):
    if t in ("Int", "Bool", "String") or t in STRUCTS or t in ENUMS:
        return True
    return (is_list(t) or is_option(t) or is_result(t)) and all(showable(a) for a in targs(t))


def fmt_of(t, e, depth=0):
    """Lean for value e of claude-lang type t in its printed form inside a list or struct, with no type
    classes, so the struct formatters can call each other in one `mutual` block."""
    if t in ("Int", "Bool"):
        return f"(toString {e})"
    if t == "String":
        return f"(clQuote {e})"
    if t in STRUCTS or t in ENUMS:
        return f"(T_{t}.clFmt {e})"
    if is_list(t) or is_option(t) or is_result(t):
        fns = []
        for j, a in enumerate(targs(t)):
            y = f"cl_y{depth}_{j}"
            fns.append(f"(fun {y} => {fmt_of(a, y, depth + 1)})")
        helper = "clFmtArray" if is_list(t) else "clFmtOption" if is_option(t) else "clFmtResult"
        return f"({helper} {' '.join(fns)} {e})"
    raise Unsupported(f"printing a `{t}`")


def type_refs(t):
    """Struct and enum names a type mentions (through lists, Option and Result too)."""
    if t in STRUCTS or t in ENUMS:
        return {t}
    if is_list(t) or is_option(t) or is_result(t):
        return set().union(*[type_refs(a) for a in targs(t)])
    return set()


def calls_in(node, out):
    """Names of every function called anywhere inside node (statements or expressions)."""
    if isinstance(node, list):
        for x in node:
            calls_in(x, out)
        return out
    if isinstance(node, tuple):
        for x in node:
            calls_in(x, out)
        return out
    if not hasattr(node, "kind") or not hasattr(node, "__dict__"):  # tokens have a kind too, but no __dict__
        return out
    if node.kind == "call":
        out.add(node.name)
    for k, v in vars(node).items():
        if k in ("tok", "name_tok", "end_tok", "var_tok", "ty", "var_ty"):
            continue
        if isinstance(v, (list, tuple)) or hasattr(v, "kind"):
            calls_in(v, out)
    return out


def nodes_of(node, kind, out=None):
    """Every AST node of this kind inside node."""
    out = [] if out is None else out
    if isinstance(node, (list, tuple)):
        for x in node:
            nodes_of(x, kind, out)
        return out
    if not hasattr(node, "kind") or not hasattr(node, "__dict__"):
        return out
    if node.kind == kind:
        out.append(node)
    for k, v in vars(node).items():
        if k not in ("tok", "name_tok", "end_tok", "var_tok", "ty", "var_ty") and (
                isinstance(v, (list, tuple)) or hasattr(v, "kind")):
            nodes_of(v, kind, out)
    return out


def side_names(e):
    """The variable one side of a comparison is about: `n`, or `xs` for `length(xs)`; else nothing."""
    if e.kind == "name" and not getattr(e, "variant", None):
        return {e.name}
    if e.kind == "call" and e.name == "length" and e.args and e.args[0][2].kind == "name":
        return {e.args[0][2].name}
    return set()


