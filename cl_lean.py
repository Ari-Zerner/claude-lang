"""Lean 4 backend for claude-lang (D26, stage 1).

Emits a Lean 4 file from the checked AST that clc.py's front end produces. `lean -c` elaborates it (which runs
the `example`s as `#eval`s, printing the same EXRUN/EXFAIL lines the C binary prints for `--cl-examples`) and
writes C, which Lean's bundled `leanc` turns into the binary.

Stage 1 covers Int, Bool, String, functions, `if`/`while`/`for`, `print` and examples; stage 2 has begun with
lists (`List[T]` is `Array T`), structs and enums (`T_Name`, fields `v_name`, variants `v_Name`), `Option`
and `Result` (`ClResult`), and `match`. Anything else raises Unsupported, which names the construct and the line.

Choices worth knowing:
- Names are prefixed (`v_x`, `f_name`) like the C backend, so no claude-lang name can collide with a Lean
  keyword or a prelude function.
- Every Int literal is written `(5 : Int)`, since an unannotated literal in Lean defaults to Nat.
- Functions are emitted callees first; a recursive group becomes `mutual partial def` (proving termination is a
  later stage). A function with no parameters takes `()`, so it isn't a constant computed at startup.
- Traps (division by zero, falling off the end of a function) are `clTrap`: `default` to the kernel, and at
  run time a flushed stdout, `file:line:col: runtime error: ...` on stderr and exit 70 (D16). `never_extract`
  stops the compiler from hoisting a constant trap into module initialization.
- `/` and `%` are Lean's (Euclidean, D27), checked for zero.
"""
