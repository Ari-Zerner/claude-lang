"""Lean 4 backend for claude-lang (D26, stage 1).

Emits a Lean 4 file from the checked AST that clc.py's front end produces. `lean -c` elaborates it (which runs
the `example`s as `#eval`s, printing the same EXRUN/EXFAIL lines the C binary prints for `--cl-examples`) and
writes C, which Lean's bundled `leanc` turns into the binary.

Stage 1 covers Int, Bool, String, functions, `if`/`while`/`for`, `print` and examples; stage 2 has begun with
lists (`List[T]` is `Array T`), structs and enums (`T_Name`, fields `v_name`, variants `v_Name`), `Option`
and `Result` (`ClResult`), and `match`. Anything else raises Unsupported, which names the construct and the line.

Choices worth knowing:
- Names are prefixed (`v_x`, `f_name`) like the C backend, so no claude-lang name can collide with a Lean
  keyword or a prelude function.
- Every Int literal is written `(5 : Int)`, since an unannotated literal in Lean defaults to Nat.
- Functions are emitted callees first; a recursive group becomes `mutual partial def` (proving termination is a
  later stage). A function with no parameters takes `()`, so it isn't a constant computed at startup.
- Traps (division by zero, falling off the end of a function) are `clTrap`: `default` to the kernel, and at
  run time a flushed stdout, `file:line:col: runtime error: ...` on stderr and exit 70 (D16). `never_extract`
  stops the compiler from hoisting a constant trap into module initialization.
- `/` and `%` are Lean's (Euclidean, D27), checked for zero.
"""
import json

PRELUDE = r'''-- Generated by clc (claude-lang) from @FILE@. Do not edit; edit the .cl file.

unsafe def clTrapImpl {α : Type} [Inhabited α] (msg : String) : α :=
  match unsafeIO (do (← IO.getStdout).flush; IO.eprintln msg; (IO.Process.exit 70 : IO α)) with
  | .ok a => a
  | .error _ => default
/-- A runtime error (D16): `default` as far as the kernel is concerned, so a proof can't use it; at run time it
prints `msg` and exits 70. -/
@[implemented_by clTrapImpl, noinline, never_extract]
def clTrap {α : Type} [Inhabited α] (msg : String) : α := default

@[inline] def clDiv (a b : Int) (msg : String) : Int := if b == 0 then clTrap msg else a / b
@[inline] def clMod (a b : Int) (msg : String) : Int := if b == 0 then clTrap msg else a % b

/-- claude-lang's printed form of a value inside a list or struct: strings quoted with the language's own
escapes, lists as `[1, 2]` (D18, D19). At the top of `print` and `{...}` a String prints as itself. -/
class ClShow (α : Type) where
  fmt : α → String
instance : ClShow Int := ⟨toString⟩
instance : ClShow Bool := ⟨toString⟩
def clQuote (s : String) : String :=
  "\"" ++ String.join (s.toList.map fun c =>
    match c with
    | '"' => "\\\"" | '\\' => "\\\\" | '\n' => "\\n" | '\t' => "\\t" | '{' => "\\{" | '}' => "\\}"
    | c => c.toString) ++ "\""
instance : ClShow String := ⟨clQuote⟩
def clFmtArray {α : Type} (f : α → String) (xs : Array α) : String := "[" ++ ", ".intercalate (xs.toList.map f) ++ "]"
instance {α : Type} [ClShow α] : ClShow (Array α) := ⟨clFmtArray ClShow.fmt⟩

/-- `Result[T, E]` (D7, D24). Not Lean's `Except`, which has no `BEq`; the names match claude-lang's. -/
inductive ClResult (α ε : Type) where
  | ok (value : α)
  | err (error : ε)
deriving BEq, Inhabited
def clFmtOption {α : Type} (f : α → String) : Option α → String
  | some x => "Some(" ++ f x ++ ")"
  | none => "None"
def clFmtResult {α ε : Type} (f : α → String) (g : ε → String) : ClResult α ε → String
  | .ok x => "Ok(" ++ f x ++ ")"
  | .err e => "Err(" ++ g e ++ ")"
instance {α : Type} [ClShow α] : ClShow (Option α) := ⟨clFmtOption ClShow.fmt⟩
instance {α ε : Type} [ClShow α] [ClShow ε] : ClShow (ClResult α ε) := ⟨clFmtResult ClShow.fmt ClShow.fmt⟩

def clIndexMsg (loc : String) (i : Int) (n : Nat) : String :=
  loc ++ ": runtime error: " ++
  if i < 0 then s!"index {i} is out of range: indexes start at 0, and there's no negative indexing (the last item is at length - 1)"
  else if n == 0 then s!"index {i} is out of range: the list is empty"
  else s!"index {i} is out of range for a list of length {n} (the last index is {n - 1})"

/-- `xs[i]`, stopping the program when i is out of range. -/
@[inline] def clGet {α : Type} [Inhabited α] (xs : Array α) (i : Int) (loc : String) : α :=
  if h : 0 ≤ i ∧ i.toNat < xs.size then xs[i.toNat]'h.2 else clTrap (clIndexMsg loc i xs.size)
/-- `xs[i] = v`; in place when xs isn't shared, which is Lean's own refcounting (D19). -/
@[inline] def clSet {α : Type} (xs : Array α) (i : Int) (v : α) (loc : String) : Array α :=
  if h : 0 ≤ i ∧ i.toNat < xs.size then xs.set i.toNat v h.2 else clTrap (clIndexMsg loc i xs.size)
/-- One step of a deeper path, `xs[i]... = v` (D23): `modify` takes the item out first, so it stays unshared. -/
@[inline] def clModify {α : Type} (xs : Array α) (i : Int) (f : α → α) (loc : String) : Array α :=
  if 0 ≤ i ∧ i.toNat < xs.size then xs.modify i.toNat f else clTrap (clIndexMsg loc i xs.size)
@[inline] def clRepeat {α : Type} (x : α) (n : Int) (msg : String) : Array α :=
  if n < 0 then clTrap msg else Array.replicate n.toNat x

def clHex (s : String) : String :=
  if s.isEmpty then "-" else
  String.join (s.toUTF8.toList.map fun b =>
    let d := "0123456789abcdef".toList
    String.ofList [d[(b.toNat / 16)]!, d[(b.toNat % 16)]!])

def clExRun (i : Nat) : IO Unit := do IO.println s!"EXRUN {i}"; (← IO.getStdout).flush
def clExBool (i : Nat) (ok : Bool) : IO Unit := do
  clExRun i
  if !ok then IO.println s!"EXFAIL {i}"
def clExShow {α : Type} [BEq α] (i : Nat) (tag : String) (l r : α) (fmt : α → String) : IO Unit := do
  clExRun i
  if !(l == r) then IO.println s!"{tag} {i} {clHex (fmt l)} {clHex (fmt r)}"
'''


class Unsupported(Exception):
    """The program uses something the Lean backend can't emit yet."""


def lean_str(t):
    out = []
    for ch in t:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


LTYPE = {"Int": "Int", "Bool": "Bool", "String": "String", "Unit": "Unit"}


STRUCTS = {}  # struct name -> its declaration; set by LeanEmitter, read by ltype and showable
ENUMS = {}  # enum name -> its declaration (variants: [(name, fields, tok)])


def targs(t):
    """The type arguments of `Option[T]` / `Result[T, E]` / `List[T]`, split at top-level commas."""
    inner, out, depth, cur = t[t.index("[") + 1:-1], [], 0, ""
    for ch in inner:
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        depth += {"[": 1, "]": -1}.get(ch, 0)
        cur += ch
    return out + [cur.strip()]


def is_option(t):
    return isinstance(t, str) and t.startswith("Option[")


def is_result(t):
    return isinstance(t, str) and t.startswith("Result[")


def is_list(t):
    return isinstance(t, str) and t.startswith("List[") and t.endswith("]")


def ltype(t, where):
    if t in LTYPE:
        return LTYPE[t]
    if is_list(t):
        return f"(Array {ltype(t[5:-1], where)})"
    if t in STRUCTS or t in ENUMS:
        return f"T_{t}"
    if is_option(t):
        return f"(Option {ltype(targs(t)[0], where)})"
    if is_result(t):
        a, b = targs(t)
        return f"(ClResult {ltype(a, where)} {ltype(b, where)})"
    raise Unsupported(f"the type `{t}` ({where})")


def showable(t):
    if t in ("Int", "Bool", "String") or t in STRUCTS or t in ENUMS:
        return True
    return (is_list(t) or is_option(t) or is_result(t)) and all(showable(a) for a in targs(t))


def fmt_of(t, e, depth=0):
    """Lean for value e of claude-lang type t in its printed form inside a list or struct, with no type
    classes, so the struct formatters can call each other in one `mutual` block."""
    if t in ("Int", "Bool"):
        return f"(toString {e})"
    if t == "String":
        return f"(clQuote {e})"
    if t in STRUCTS or t in ENUMS:
        return f"(T_{t}.clFmt {e})"
    if is_list(t) or is_option(t) or is_result(t):
        fns = []
        for j, a in enumerate(targs(t)):
            y = f"cl_y{depth}_{j}"
            fns.append(f"(fun {y} => {fmt_of(a, y, depth + 1)})")
        helper = "clFmtArray" if is_list(t) else "clFmtOption" if is_option(t) else "clFmtResult"
        return f"({helper} {' '.join(fns)} {e})"
    raise Unsupported(f"printing a `{t}`")


def type_refs(t):
    """Struct and enum names a type mentions (through lists, Option and Result too)."""
    if t in STRUCTS or t in ENUMS:
        return {t}
    if is_list(t) or is_option(t) or is_result(t):
        return set().union(*[type_refs(a) for a in targs(t)])
    return set()


def calls_in(node, out):
    """Names of every function called anywhere inside node (statements or expressions)."""
    if isinstance(node, list):
        for x in node:
            calls_in(x, out)
        return out
    if isinstance(node, tuple):
        for x in node:
            calls_in(x, out)
        return out
    if not hasattr(node, "kind") or not hasattr(node, "__dict__"):  # tokens have a kind too, but no __dict__
        return out
    if node.kind == "call":
        out.add(node.name)
    for k, v in vars(node).items():
        if k in ("tok", "name_tok", "end_tok", "var_tok", "ty", "var_ty"):
            continue
        if isinstance(v, (list, tuple)) or hasattr(v, "kind"):
            calls_in(v, out)
    return out


def sccs(names, edges):
    """Tarjan's algorithm. Returns strongly connected components, each after every component it calls."""
    index, low, stack, on, out = {}, {}, [], set(), []
    counter = [0]

    def visit(v):
        index[v] = low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        on.add(v)
        for w in edges[v]:
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w == v:
                    break
            out.append(sorted(comp, key=names.index))
    for v in names:
        if v not in index:
            visit(v)
    return out


def ends_in_return(stmts):
    """Does this block's last statement return on every path, as far as Lean's `do` sees it?"""
    stmts = [x for x in stmts if x.kind != "example"]
    if not stmts:
        return False
    s = stmts[-1]
    if s.kind == "return":
        return True
    if s.kind == "if":
        return s.else_body is not None and ends_in_return(s.else_body) and all(
            ends_in_return(b) for _, b in s.branches)
    if s.kind == "match":  # the checker made it exhaustive
        return bool(s.arms) and all(ends_in_return(b) for _, b, _ in s.arms)
    return False


class LeanEmitter:
    def __init__(self, fns, structs, path):
        self.fns, self.path = fns, path
        self.types = [st for st in structs if st.name != "?"]
        STRUCTS.clear()
        STRUCTS.update({st.name: st for st in self.types if st.kind == "struct"})
        ENUMS.clear()
        ENUMS.update({st.name: st for st in self.types if st.kind == "enum"})
        self.by_name = {f.name: f for f in fns}
        self.examples = [s for f in fns for s in f.body if s.kind == "example"]
        self.tmp = 0

    def loc(self, tok):
        return f"{self.path}:{tok.line}:{tok.col}"

    def trap_msg(self, tok, what):
        return lean_str(f"{self.loc(tok)}: runtime error: {what}")

    # -- top level

    def emit(self):
        out = [PRELUDE.replace("@FILE@", json.dumps(self.path))]
        self.type_decls(out)
        names = [f.name for f in self.fns]
        # Examples aren't part of the function, so a function whose examples call it isn't recursive.
        edges = {f.name: sorted(n for n in calls_in([s for s in f.body if s.kind != "example"], set())
                                if n in self.by_name) for f in self.fns}
        for comp in sccs(names, edges):
            recursive = len(comp) > 1 or comp[0] in edges[comp[0]]
            if len(comp) > 1:
                out.append("mutual")
            for name in comp:
                out.append("")
                self.function(self.by_name[name], recursive, out)
            if len(comp) > 1:
                out.append("")
                out.append("end")
        out.append("")
        out.append("-- examples (D8), run while Lean elaborates this file")
        for i, s in enumerate(self.examples):
            out.append(self.example(i, s))
        out.append('#eval IO.println "EXDONE"')
        out.append("")
        if "main" in self.by_name:
            io = self.by_name["main"].uses_io
            out.append("def main : IO Unit := f_main ()" if io else "def main : IO Unit := pure (f_main ())")
        return "\n".join(out) + "\n"

    def type_decls(self, out):
        """Structs (D22) as Lean structures and enums (D24) as inductives, each after the types it uses. A type
        can contain itself (a struct only through a list), which Lean takes as a (nested) inductive. Then one
        formatter per type, all in one `mutual` block, since formatters of types inside each other call each
        other."""
        if not self.types:
            return

        def fields_of(st):
            return st.fields if st.kind == "struct" else [f for _, fs, _ in st.variants for f in fs]
        names = [st.name for st in self.types]
        edges = {st.name: sorted(set().union(*[type_refs(t) for _, t, _ in fields_of(st)]) - {st.name})
                 for st in self.types}
        for comp in sccs(names, edges):
            if len(comp) > 1:
                raise Unsupported(f"types that contain each other ({', '.join(comp)})")
            st = next(x for x in self.types if x.name == comp[0])
            if st.kind == "struct":
                out.append(f"structure T_{st.name} where")
                for fname, t, _ in st.fields:
                    out.append(f"  v_{fname} : {ltype(t, f'field `{fname}` of struct {st.name}')}")
            else:
                out.append(f"inductive T_{st.name} where")
                for vname, fs, _ in st.variants:
                    args = "".join(f" (v_{fn} : {ltype(t, f'field `{fn}` of {vname}')})" for fn, t, _ in fs)
                    out.append(f"  | v_{vname}{args}")
            out.append("deriving BEq, Inhabited")
            out.append("")
        many = len(self.types) > 1
        if many:
            out.append("mutual")
        for st in self.types:
            out.append(f"partial def T_{st.name}.clFmt (r : T_{st.name}) : String :=")
            if st.kind == "struct":
                out.append("  " + self.fmt_fields(st.name, [(fn, t, f"r.v_{fn}") for fn, t, _ in st.fields]))
                continue
            out.append("  match r with")
            for vname, fs, _ in st.variants:
                binds = [f"c{j}" for j in range(len(fs))]
                text = (self.fmt_fields(vname, [(fn, t, binds[j]) for j, (fn, t, _) in enumerate(fs)]) if fs
                        else lean_str(vname))
                out.append(f"  | .v_{vname}{''.join(' ' + b for b in binds)} => {text}")
        if many:
            out.append("end")
        for st in self.types:
            out.append(f"instance : ClShow T_{st.name} := ⟨T_{st.name}.clFmt⟩")
        out.append("")

    def fmt_fields(self, name, fields):
        """`Name(a: 1, b: "x")`, the way one is made (D22, D24)."""
        parts = [lean_str(f"{name}(")]
        for j, (fname, t, e) in enumerate(fields):
            parts.append(lean_str(f"{', ' if j else ''}{fname}: "))
            parts.append(fmt_of(t, e))
        parts.append(lean_str(")"))
        return " ++ ".join(parts)

    def function(self, f, recursive, out):
        self.cur = f
        params = " ".join(f"(v_{n} : {ltype(t, f'parameter `{n}` of fn {f.name}')})" for n, t, _ in f.params)
        params = params or "(_ : Unit)"
        ret = ltype(f.ret, f"result of fn {f.name}")
        head = "partial def" if recursive else "def"
        if f.uses_io:
            out.append(f"{head} f_{f.name} {params} : IO {ret} := do")
        else:
            out.append(f"{head} f_{f.name} {params} : {ret} := Id.run do")
        body = []
        self.block(f.body, 1, body)
        if f.ret != "Unit" and not ends_in_return(f.body):
            msg = self.trap_msg(f.end_tok, f"reached the end of fn {f.name} without a return")
            body.append(f"  return clTrap {msg}")
        out.extend(body or ["  pure ()"])

    def example(self, i, s):
        e = s.expr
        if e.kind == "bin" and e.op == "==" and not e.paren and showable(e.left.ty):
            tag, fmt = ("EXFAILS", "id") if e.left.ty == "String" else ("EXFAILV", "ClShow.fmt")
            ty = ltype(e.left.ty, "an example")
            return f"#eval clExShow {i} {json.dumps(tag)} ({self.expr(e.left)} : {ty}) {self.expr(e.right)} {fmt}"
        return f"#eval clExBool {i} {self.expr(e)}"

    # -- statements

    def block(self, stmts, depth, out):
        ind = "  " * depth
        start = len(out)
        for s in stmts:
            k = s.kind
            if k == "example":
                continue
            if k == "let":
                if s.name == "_":
                    out.append(f"{ind}let _ := {self.expr(s.expr)}")
                else:
                    mut = "mut " if s.mutable else ""
                    out.append(f"{ind}let {mut}v_{s.name} : {ltype(s.var_ty, f'`{s.name}`')} := {self.expr(s.expr)}")
            elif k == "assign":
                out.append(f"{ind}v_{s.name} := {self.expr(s.expr)}")
            elif k in ("setindex", "setfield"):
                self.set_path(s, ind, out)
            elif k == "return":
                out.append(f"{ind}return" if s.expr is None else f"{ind}return {self.expr(s.expr)}")
            elif k == "if":
                for j, (c, body) in enumerate(s.branches):
                    out.append(f"{ind}{'if' if j == 0 else 'else if'} {self.expr(c)} then")
                    self.block(body, depth + 1, out)
                if s.else_body is not None:
                    out.append(f"{ind}else")
                    self.block(s.else_body, depth + 1, out)
            elif k == "match":
                self.match_stmt(s, depth, out)
            elif k == "while":
                out.append(f"{ind}while {self.expr(s.cond)} do")
                self.block(s.body, depth + 1, out)
            elif k == "for":
                self.for_stmt(s, depth, out)
            elif k in ("break", "continue"):
                out.append(f"{ind}{k}")
            elif k == "exprstmt":
                e = s.expr
                if e.kind == "call" and (e.name == "print" or self.is_io(e)):
                    out.append(f"{ind}{self.call(e, bare=True)}")
                else:
                    out.append(f"{ind}let _ := {self.expr(e)}")
            else:
                raise Unsupported(f"`{k}` statements (line {s.tok.line})")
        if len(out) == start:
            out.append(f"{ind}pure ()")

    def for_stmt(self, s, depth, out):
        """Bounds are evaluated once, lo first. Counting forwards uses Lean's Int ranges; backwards counts a
        Nat-free offset k up from 0 and derives the variable from it, so `continue` needs no step of its own."""
        ind = "  " * depth
        v = f"v_{s.var}"
        if s.src is not None:
            # Lean's `for` holds the array it started with, so changing the list inside the loop changes a
            # copy and the loop walks the original: the snapshot D21 asks for.
            src = self.expr(s.src)
            out.append(f"{ind}for {v} in {src}{'.reverse' if s.rev else ''} do")
            self.block(s.body, depth + 1, out)
            return
        if not s.rev:
            rng = "...=" if s.incl else "...<"
            out.append(f"{ind}for {v} in {self.expr(s.lo)}{rng}{self.expr(s.hi)} do")
            self.block(s.body, depth + 1, out)
            return
        self.tmp += 1
        lo, hi, k = f"cl_lo{self.tmp}", f"cl_hi{self.tmp}", f"cl_k{self.tmp}"
        out.append(f"{ind}let {lo} : Int := {self.expr(s.lo)}")
        out.append(f"{ind}let {hi} : Int := {self.expr(s.hi)}")
        count = f"({hi} - {lo} + 1)" if s.incl else f"({hi} - {lo})"
        top = hi if s.incl else f"({hi} - 1)"
        out.append(f"{ind}for {k} in (0 : Int)...<{count} do")
        out.append(f"{ind}  let {v} : Int := {top} - {k}")
        self.block(s.body, depth + 1, out)

    def match_stmt(self, s, depth, out):
        """A `do`-block `match`, so `break`, `continue` and `return` in an arm act on the enclosing loop or
        function, as in C (D24). Fields are bound by position in the constructor; unbound ones are `_`."""
        ind = "  " * depth
        t = s.subj.ty
        out.append(f"{ind}match {self.expr(s.subj)} with")
        for pat, body, _ in s.arms:
            if pat.variant == "_":
                out.append(f"{ind}| _ =>")
            else:
                if t in ENUMS:
                    con = f"T_{t}.v_{pat.variant}"
                    nfields = len(ENUMS[t].variants[pat.tag][1])
                else:
                    con = {"Some": "some", "None": "none", "Ok": "ClResult.ok", "Err": "ClResult.err"}[pat.variant]
                    nfields = 0 if pat.variant == "None" else 1
                args = ["_"] * nfields
                for fk, name, _ in pat.slots:
                    args[fk] = f"v_{name}"
                out.append(f"{ind}| {con}{''.join(' ' + a for a in args)} =>")
            self.block(body, depth + 1, out)

    def set_path(self, s, ind, out):
        """`xs[i] = v` and deeper paths like `grid[i][j] = v` (D23), in C's order: the value first, then the
        indexes left to right, then the walk down, which checks each index as it reaches it."""
        tgt = s.target
        steps, n = [], tgt
        while n.kind in ("index", "field"):
            steps.append(n)
            n = n.base
        steps.reverse()
        self.tmp += 1
        t = self.tmp
        out.append(f"{ind}let cl_v{t} := {self.expr(s.expr)}")
        for j, x in enumerate(steps):
            if x.kind == "index":
                out.append(f"{ind}let cl_i{t}_{j} : Int := {self.expr(x.index)}")

        def update(j, cur):
            """A field step is `{ r with f := ... }`, which Lean does in place when r isn't shared (its
            reset/reuse also leaves the field's old value unshared, so a list inside stays in place too)."""
            x = steps[j]
            last = j == len(steps) - 1
            if x.kind == "field":
                inner = f"cl_v{t}" if last else update(j + 1, f"{cur}.v_{x.name}")
                return f"{{ {cur} with v_{x.name} := {inner} }}"
            loc = lean_str(self.loc(x.tok))
            if last:
                return f"clSet {cur} cl_i{t}_{j} cl_v{t} {loc}"
            return f"clModify {cur} cl_i{t}_{j} (fun cl_r{j} => {update(j + 1, f'cl_r{j}')}) {loc}"
        out.append(f"{ind}v_{n.name} := {update(0, f'v_{n.name}')}")

    # -- expressions

    def is_io(self, e):
        f = self.by_name.get(e.name)
        return e.name == "print" or (f is not None and f.uses_io)

    def show(self, e):
        """Lean for e as a String (interpolation and print)."""
        if e.ty == "String":
            return self.expr(e)
        if e.ty in ("Int", "Bool"):
            return f"(toString {self.expr(e)})"
        if showable(e.ty):
            return f"(ClShow.fmt {self.expr(e)})"
        raise Unsupported(f"showing a `{e.ty}` (line {e.tok.line})")

    def expr(self, e):
        k = e.kind
        if k == "int":
            return f"({e.value} : Int)"
        if k == "bool":
            return "true" if e.value else "false"
        if k == "str":
            pieces = [lean_str(p) if kind == "text" else self.show(p) for kind, p in e.parts]
            if not pieces:
                return '""'
            return pieces[0] if len(pieces) == 1 and e.parts[0][0] == "text" else "(" + " ++ ".join(pieces) + ")"
        if k == "list":
            items = ", ".join(self.expr(x) for x in e.items)
            return f"(#[{items}] : {ltype(e.ty, 'a list')})"
        if k == "index":
            return f"(clGet {self.expr(e.base)} {self.expr(e.index)} {lean_str(self.loc(e.tok))})"
        if k == "field":
            return f"{self.expr(e.base)}.v_{e.name}"
        if k == "name":
            if getattr(e, "variant", None):
                if e.variant[0] == "Option":
                    return f"(none : {ltype(e.ty, 'None')})"
                return f"T_{e.variant[0]}.v_{e.name}"
            return f"v_{e.name}"
        if k == "neg":
            return f"(-{self.expr(e.expr)})"
        if k == "not":
            return f"(!{self.expr(e.expr)})"
        if k == "bin":
            if e.left.ty not in ("Int", "Bool", "String") and not (showable(e.left.ty) and e.op in ("==", "!=")):
                raise Unsupported(f"`{e.op}` on `{e.left.ty}` (line {e.tok.line})")
            l, r = self.expr(e.left), self.expr(e.right)
            if e.op == "/":
                return f"(clDiv {l} {r} {self.trap_msg(e.tok, 'division by zero')})"
            if e.op == "%":
                return f"(clMod {l} {r} {self.trap_msg(e.tok, 'division by zero in `%`')})"
            if e.op in ("+", "-", "*"):
                return f"({l} {e.op} {r})"
            if e.op in ("==", "!="):
                return f"({l} {e.op} {r})"
            if e.op in ("<", "<=", ">", ">="):
                return f"(decide ({l} {e.op} {r}))"
            if e.op in ("and", "or"):
                return f"({l} {'&&' if e.op == 'and' else '||'} {r})"
            raise Unsupported(f"the operator `{e.op}` (line {e.tok.line})")
        if k == "call":
            return self.call(e)
        raise Unsupported(f"`{k}` expressions (line {e.tok.line})")

    def call(self, e, bare=False):
        """A call. An io call inside an expression is lifted with `(← ...)`; as a statement it's `bare`."""
        if getattr(e, "variant", None) or getattr(e, "ctor", False):
            # Point(x: 1, y: 2), Moved(x: 1, y: 2), Some(3): the fields in declared order (D22, D24)
            vals = [None] * len(e.args)
            for i, (_, _, a) in enumerate(e.args):
                vals[e.order[i]] = self.expr(a)
            args = " ".join(vals)
            if getattr(e, "ctor", False):
                return f"(T_{e.name}.mk {args})"
            if e.variant[0] == "Option":
                return f"(some {args})"
            if e.variant[0] == "Result":
                return f"(ClResult.{'ok' if e.name == 'Ok' else 'err'} {args} : {ltype(e.ty, e.name)})"
            return f"(T_{e.variant[0]}.v_{e.name} {args})"
        if e.name == "print":
            a = e.args[0][2]
            c = f"IO.println {self.show(a)}"
        elif e.name == "length":
            a = e.args[0][2]
            return f"(Int.ofNat {self.expr(a)}.{'length' if a.ty == 'String' else 'size'})"
        elif e.name in ("append", "repeat"):
            by = {n: a for n, _, a in e.args}
            if e.name == "append":
                # xs = append(list: xs, item: x) pushes in place when xs isn't shared (Lean's refcounting).
                return f"({self.expr(by['list'])}.push {self.expr(by['item'])})"
            msg = self.trap_msg(e.tok, "`repeat` needs `times` to be 0 or more")
            return f"(clRepeat {self.expr(by['item'])} {self.expr(by['times'])} {msg})"
        elif e.name in self.by_name:
            args = " ".join(self.expr(a) for _, _, a in e.args) or "()"
            c = f"f_{e.name} {args}"
        else:
            raise Unsupported(f"the built-in `{e.name}` (line {e.tok.line})")
        if bare:
            return c
        return f"(← {c})" if self.is_io(e) else f"({c})"
