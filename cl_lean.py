"""Lean 4 backend for claude-lang (D26, stage 1).

Emits a Lean 4 file from the checked AST that clc.py's front end produces. `lean -c` elaborates it (which runs
the `example`s as `#eval`s, printing the same EXRUN/EXFAIL lines the C binary prints for `--cl-examples`) and
writes C, which Lean's bundled `leanc` turns into the binary.

Stage 1 covers Int, Bool, String, functions, `if`/`while`/`for` over numbers, `print` and examples. Anything
else raises Unsupported, which names the construct and the line.

Choices worth knowing:
- Names are prefixed (`v_x`, `f_name`) like the C backend, so no claude-lang name can collide with a Lean
  keyword or a prelude function.
- Every Int literal is written `(5 : Int)`, since an unannotated literal in Lean defaults to Nat.
- Functions are emitted callees first; a recursive group becomes `mutual partial def` (proving termination is a
  later stage). A function with no parameters takes `()`, so it isn't a constant computed at startup.
- Traps (division by zero, falling off the end of a function) are `clTrap`: `default` to the kernel, and at
  run time a flushed stdout, `file:line:col: runtime error: ...` on stderr and exit 70 (D16). `never_extract`
  stops the compiler from hoisting a constant trap into module initialization.
- `/` and `%` are Lean's (Euclidean, D27), checked for zero.
"""
import json

PRELUDE = r'''-- Generated by clc (claude-lang) from @FILE@. Do not edit; edit the .cl file.

unsafe def clTrapImpl {α : Type} [Inhabited α] (msg : String) : α :=
  match unsafeIO (do (← IO.getStdout).flush; IO.eprintln msg; (IO.Process.exit 70 : IO α)) with
  | .ok a => a
  | .error _ => default
/-- A runtime error (D16): `default` as far as the kernel is concerned, so a proof can't use it; at run time it
prints `msg` and exits 70. -/
@[implemented_by clTrapImpl, noinline, never_extract]
def clTrap {α : Type} [Inhabited α] (msg : String) : α := default

@[inline] def clDiv (a b : Int) (msg : String) : Int := if b == 0 then clTrap msg else a / b
@[inline] def clMod (a b : Int) (msg : String) : Int := if b == 0 then clTrap msg else a % b

def clHex (s : String) : String :=
  if s.isEmpty then "-" else
  String.join (s.toUTF8.toList.map fun b =>
    let d := "0123456789abcdef".toList
    String.mk [d[(b.toNat / 16)]!, d[(b.toNat % 16)]!])

def clExRun (i : Nat) : IO Unit := do IO.println s!"EXRUN {i}"; (← IO.getStdout).flush
def clExBool (i : Nat) (ok : Bool) : IO Unit := do
  clExRun i
  if !ok then IO.println s!"EXFAIL {i}"
def clExShow {α : Type} [BEq α] [ToString α] (i : Nat) (tag : String) (l r : α) : IO Unit := do
  clExRun i
  if !(l == r) then IO.println s!"{tag} {i} {clHex (toString l)} {clHex (toString r)}"
'''


class Unsupported(Exception):
    """The program uses something the Lean backend can't emit yet."""


def lean_str(t):
    out = []
    for ch in t:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


LTYPE = {"Int": "Int", "Bool": "Bool", "String": "String", "Unit": "Unit"}


def ltype(t, where):
    if t in LTYPE:
        return LTYPE[t]
    raise Unsupported(f"the type `{t}` ({where})")


def calls_in(node, out):
    """Names of every function called anywhere inside node (statements or expressions)."""
    if isinstance(node, list):
        for x in node:
            calls_in(x, out)
        return out
    if isinstance(node, tuple):
        for x in node:
            calls_in(x, out)
        return out
    if not hasattr(node, "kind") or not hasattr(node, "__dict__"):  # tokens have a kind too, but no __dict__
        return out
    if node.kind == "call":
        out.add(node.name)
    for k, v in vars(node).items():
        if k in ("tok", "name_tok", "end_tok", "var_tok", "ty", "var_ty"):
            continue
        if isinstance(v, (list, tuple)) or hasattr(v, "kind"):
            calls_in(v, out)
    return out


def sccs(names, edges):
    """Tarjan's algorithm. Returns strongly connected components, each after every component it calls."""
    index, low, stack, on, out = {}, {}, [], set(), []
    counter = [0]

    def visit(v):
        index[v] = low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        on.add(v)
        for w in edges[v]:
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w == v:
                    break
            out.append(sorted(comp, key=names.index))
    for v in names:
        if v not in index:
            visit(v)
    return out


def ends_in_return(stmts):
    """Does this block's last statement return on every path, as far as Lean's `do` sees it?"""
    stmts = [x for x in stmts if x.kind != "example"]
    if not stmts:
        return False
    s = stmts[-1]
    if s.kind == "return":
        return True
    if s.kind == "if":
        return s.else_body is not None and ends_in_return(s.else_body) and all(
            ends_in_return(b) for _, b in s.branches)
    return False


class LeanEmitter:
    def __init__(self, fns, structs, path):
        self.fns, self.path = fns, path
        if any(st.name != "?" for st in structs):
            st = next(st for st in structs if st.name != "?")
            raise Unsupported(f"`{st.kind} {st.name}` (line {st.tok.line}): structs and enums")
        self.by_name = {f.name: f for f in fns}
        self.examples = [s for f in fns for s in f.body if s.kind == "example"]
        self.tmp = 0

    def loc(self, tok):
        return f"{self.path}:{tok.line}:{tok.col}"

    def trap_msg(self, tok, what):
        return lean_str(f"{self.loc(tok)}: runtime error: {what}")

    # -- top level

    def emit(self):
        out = [PRELUDE.replace("@FILE@", json.dumps(self.path))]
        names = [f.name for f in self.fns]
        # Examples aren't part of the function, so a function whose examples call it isn't recursive.
        edges = {f.name: sorted(n for n in calls_in([s for s in f.body if s.kind != "example"], set())
                                if n in self.by_name) for f in self.fns}
        for comp in sccs(names, edges):
            recursive = len(comp) > 1 or comp[0] in edges[comp[0]]
            if len(comp) > 1:
                out.append("mutual")
            for name in comp:
                out.append("")
                self.function(self.by_name[name], recursive, out)
            if len(comp) > 1:
                out.append("")
                out.append("end")
        out.append("")
        out.append("-- examples (D8), run while Lean elaborates this file")
        for i, s in enumerate(self.examples):
            out.append(self.example(i, s))
        out.append('#eval IO.println "EXDONE"')
        out.append("")
        if "main" in self.by_name:
            io = self.by_name["main"].uses_io
            out.append("def main : IO Unit := f_main ()" if io else "def main : IO Unit := pure (f_main ())")
        return "\n".join(out) + "\n"

    def function(self, f, recursive, out):
        self.cur = f
        params = " ".join(f"(v_{n} : {ltype(t, f'parameter `{n}` of fn {f.name}')})" for n, t, _ in f.params)
        params = params or "(_ : Unit)"
        ret = ltype(f.ret, f"result of fn {f.name}")
        head = "partial def" if recursive else "def"
        if f.uses_io:
            out.append(f"{head} f_{f.name} {params} : IO {ret} := do")
        else:
            out.append(f"{head} f_{f.name} {params} : {ret} := Id.run do")
        body = []
        self.block(f.body, 1, body)
        if f.ret != "Unit" and not ends_in_return(f.body):
            msg = self.trap_msg(f.end_tok, f"reached the end of fn {f.name} without a return")
            body.append(f"  return clTrap {msg}")
        out.extend(body or ["  pure ()"])

    def example(self, i, s):
        e = s.expr
        if e.kind == "bin" and e.op == "==" and not e.paren and e.left.ty in ("Int", "Bool", "String"):
            tag = "EXFAILS" if e.left.ty == "String" else "EXFAILV"
            return f"#eval clExShow {i} {json.dumps(tag)} {self.expr(e.left)} {self.expr(e.right)}"
        return f"#eval clExBool {i} {self.expr(e)}"

    # -- statements

    def block(self, stmts, depth, out):
        ind = "  " * depth
        start = len(out)
        for s in stmts:
            k = s.kind
            if k == "example":
                continue
            if k == "let":
                if s.name == "_":
                    out.append(f"{ind}let _ := {self.expr(s.expr)}")
                else:
                    mut = "mut " if s.mutable else ""
                    out.append(f"{ind}let {mut}v_{s.name} : {ltype(s.var_ty, f'`{s.name}`')} := {self.expr(s.expr)}")
            elif k == "assign":
                out.append(f"{ind}v_{s.name} := {self.expr(s.expr)}")
            elif k == "return":
                out.append(f"{ind}return" if s.expr is None else f"{ind}return {self.expr(s.expr)}")
            elif k == "if":
                for j, (c, body) in enumerate(s.branches):
                    out.append(f"{ind}{'if' if j == 0 else 'else if'} {self.expr(c)} then")
                    self.block(body, depth + 1, out)
                if s.else_body is not None:
                    out.append(f"{ind}else")
                    self.block(s.else_body, depth + 1, out)
            elif k == "while":
                out.append(f"{ind}while {self.expr(s.cond)} do")
                self.block(s.body, depth + 1, out)
            elif k == "for":
                self.for_stmt(s, depth, out)
            elif k in ("break", "continue"):
                out.append(f"{ind}{k}")
            elif k == "exprstmt":
                e = s.expr
                if e.kind == "call" and (e.name == "print" or self.is_io(e)):
                    out.append(f"{ind}{self.call(e, bare=True)}")
                else:
                    out.append(f"{ind}let _ := {self.expr(e)}")
            else:
                raise Unsupported(f"`{k}` statements (line {s.tok.line})")
        if len(out) == start:
            out.append(f"{ind}pure ()")

    def for_stmt(self, s, depth, out):
        """Bounds are evaluated once, lo first. Counting forwards uses Lean's Int ranges; backwards counts a
        Nat-free offset k up from 0 and derives the variable from it, so `continue` needs no step of its own."""
        ind = "  " * depth
        if s.src is not None:
            raise Unsupported(f"`for` over a list (line {s.tok.line})")
        v = f"v_{s.var}"
        if not s.rev:
            rng = "...=" if s.incl else "...<"
            out.append(f"{ind}for {v} in {self.expr(s.lo)}{rng}{self.expr(s.hi)} do")
            self.block(s.body, depth + 1, out)
            return
        self.tmp += 1
        lo, hi, k = f"cl_lo{self.tmp}", f"cl_hi{self.tmp}", f"cl_k{self.tmp}"
        out.append(f"{ind}let {lo} : Int := {self.expr(s.lo)}")
        out.append(f"{ind}let {hi} : Int := {self.expr(s.hi)}")
        count = f"({hi} - {lo} + 1)" if s.incl else f"({hi} - {lo})"
        top = hi if s.incl else f"({hi} - 1)"
        out.append(f"{ind}for {k} in (0 : Int)...<{count} do")
        out.append(f"{ind}  let {v} : Int := {top} - {k}")
        self.block(s.body, depth + 1, out)

    # -- expressions

    def is_io(self, e):
        f = self.by_name.get(e.name)
        return e.name == "print" or (f is not None and f.uses_io)

    def show(self, e):
        """Lean for e as a String (interpolation and print)."""
        if e.ty == "String":
            return self.expr(e)
        if e.ty in ("Int", "Bool"):
            return f"(toString {self.expr(e)})"
        raise Unsupported(f"showing a `{e.ty}` (line {e.tok.line})")

    def expr(self, e):
        k = e.kind
        if k == "int":
            return f"({e.value} : Int)"
        if k == "bool":
            return "true" if e.value else "false"
        if k == "str":
            pieces = [lean_str(p) if kind == "text" else self.show(p) for kind, p in e.parts]
            if not pieces:
                return '""'
            return pieces[0] if len(pieces) == 1 and e.parts[0][0] == "text" else "(" + " ++ ".join(pieces) + ")"
        if k == "name":
            if getattr(e, "variant", None):
                raise Unsupported(f"enum variants (line {e.tok.line})")
            return f"v_{e.name}"
        if k == "neg":
            return f"(-{self.expr(e.expr)})"
        if k == "not":
            return f"(!{self.expr(e.expr)})"
        if k == "bin":
            if e.left.ty not in ("Int", "Bool", "String"):
                raise Unsupported(f"`{e.op}` on `{e.left.ty}` (line {e.tok.line})")
            l, r = self.expr(e.left), self.expr(e.right)
            if e.op == "/":
                return f"(clDiv {l} {r} {self.trap_msg(e.tok, 'division by zero')})"
            if e.op == "%":
                return f"(clMod {l} {r} {self.trap_msg(e.tok, 'division by zero in `%`')})"
            if e.op in ("+", "-", "*"):
                return f"({l} {e.op} {r})"
            if e.op in ("==", "!="):
                return f"({l} {e.op} {r})"
            if e.op in ("<", "<=", ">", ">="):
                return f"(decide ({l} {e.op} {r}))"
            if e.op in ("and", "or"):
                return f"({l} {'&&' if e.op == 'and' else '||'} {r})"
            raise Unsupported(f"the operator `{e.op}` (line {e.tok.line})")
        if k == "call":
            return self.call(e)
        raise Unsupported(f"`{k}` expressions (line {e.tok.line})")

    def call(self, e, bare=False):
        """A call. An io call inside an expression is lifted with `(← ...)`; as a statement it's `bare`."""
        if getattr(e, "variant", None) or getattr(e, "ctor", False):
            raise Unsupported(f"constructing `{e.name}` (line {e.tok.line})")
        if e.name == "print":
            a = e.args[0][2]
            c = f"IO.println {self.show(a)}"
        elif e.name == "length":
            a = e.args[0][2]
            if a.ty != "String":
                raise Unsupported(f"`length` of a `{a.ty}` (line {e.tok.line})")
            return f"(Int.ofNat {self.expr(a)}.length)"
        elif e.name in self.by_name:
            args = " ".join(self.expr(a) for _, _, a in e.args) or "()"
            c = f"f_{e.name} {args}"
        else:
            raise Unsupported(f"the built-in `{e.name}` (line {e.tok.line})")
        if bare:
            return c
        return f"(← {c})" if self.is_io(e) else f"({c})"
